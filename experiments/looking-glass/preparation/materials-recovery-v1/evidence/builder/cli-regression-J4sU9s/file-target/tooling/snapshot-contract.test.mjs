import assert from 'node:assert/strict';
import { join, resolve } from 'node:path';
import { readJson } from './package-utils.mjs';
import { validateJson } from './schema-validator.mjs';
import { validateSnapshotRecord } from './snapshot-contract.mjs';

const base = resolve(import.meta.dirname, '..');
const world = readJson(join(base, 'design/world.json'));
const allocations = readJson(join(base, 'design/allocations.json'));
const development = readJson(join(base, 'design/development-tasks.json'));
const schema = readJson(join(base, 'design/snapshot.schema.json'));
const packet = allocations.packets[0];
const zeroHash = '0'.repeat(64);
const initialContext = { phase: 'initial', agentId: 'A1', snapshotId: 'SYNTHETIC_VALID_NOT_RESEARCH_OUTPUT', modelId: 'SYNTHETIC_FIXTURE_NO_MODEL_RUN', modelVersion: 'none', cardIds: packet.cardIds, inputManifestSha256: zeroHash, settingsManifestSha256: zeroHash };
const unionContext = { phase: 'union', agentId: 'SYNTHETIC-UNION', snapshotId: 'SYNTHETIC_VALID_UNION_NOT_RESEARCH_OUTPUT', modelId: 'SYNTHETIC_FIXTURE_NO_MODEL_RUN', modelVersion: 'none', cardIds: world.cards.map(card => card.id), inputManifestSha256: zeroHash, settingsManifestSha256: zeroHash };
const validate = (record, context = initialContext) => validateSnapshotRecord(record, schema, world, allocations, context, development);
const fixture = name => readJson(join(import.meta.dirname, 'fixtures', name));
const valid = fixture('SYNTHETIC_VALID_NOT_RESEARCH_OUTPUT.json');
assert.deepEqual(validate(valid), []);
const badFalse = fixture('SYNTHETIC_INVALID_FALSE_AS_UNKNOWN_NOT_RESEARCH_OUTPUT.json');
assert.match(validate(badFalse).join(' '), /outside enum/);
const badCommitment = fixture('SYNTHETIC_INVALID_ENDORSEMENT_AS_COMMITMENT_NOT_RESEARCH_OUTPUT.json');
assert.deepEqual(validateJson(badCommitment, schema), []); // semantic check adds value beyond JSON shape
assert.match(validate(badCommitment).join(' '), /does not positively support this exact predicate/);
const altered = structuredClone(valid);
altered.interpretations[0].supportingClaimIds = ['F-C18-1'];
assert.match(validate(altered).join(' '), /outside supplied cards/);
const missingNested = structuredClone(valid);
delete missingNested.interpretations[0].arguments;
assert.match(validate(missingNested).join(' '), /required/);
const unknownAsRefuted = structuredClone(valid);
unknownAsRefuted.interpretations[3].status = 'refuted';
assert.match(validate(unknownAsRefuted).join(' '), /status refuted differs from evidence pair unknown/);
const unknownWithEvidence = structuredClone(valid);
unknownWithEvidence.interpretations[3].supportingClaimIds = ['F-C04-1'];
assert.match(validate(unknownWithEvidence).join(' '), /status unknown differs from evidence pair supported/);
const wrongPlanCommitment = structuredClone(valid);
wrongPlanCommitment.interpretations[2].supportingClaimIds = ['F-C04-4'];
assert.match(validate(wrongPlanCommitment).join(' '), /does not positively support this exact predicate/);
const attributionAsAttestation = structuredClone(valid);
attributionAsAttestation.interpretations[1].sourceKind = 'model_attribution';
assert.match(validate(attributionAsAttestation).join(' '), /cannot become actor attestation/);
const unsupportedTask = structuredClone(valid);
unsupportedTask.taskResponses[0].taskId = 'D09';
assert.match(validate(unsupportedTask).join(' '), /outside phase task allowlist/);
const wrongAgent = structuredClone(valid);
wrongAgent.agentId = 'A4';
assert.match(validate(wrongAgent).join(' '), /agentId differs from trusted expected context/);
assert.match(validate(wrongAgent, { ...initialContext, agentId: 'A4' }).join(' '), /agentId\/cardIds differ from authored allocation/);
const duplicateInterpretation = structuredClone(valid);
duplicateInterpretation.interpretations[1].id = duplicateInterpretation.interpretations[0].id;
assert.match(validate(duplicateInterpretation).join(' '), /interpretation IDs must be unique/);
const supportedWithoutReadiness = structuredClone(valid);
supportedWithoutReadiness.proposedActions[0].status = 'supported';
supportedWithoutReadiness.proposedActions[0].missingDependencies = [];
assert.match(validate(supportedWithoutReadiness).join(' '), /supported action lacks supported D07 readiness/);
const supportedWithUnprovenComponents = structuredClone(supportedWithoutReadiness);
supportedWithUnprovenComponents.taskResponses.find(response => response.taskId === 'D07').values['P12.readiness'] = 'supported';
assert.match(validate(supportedWithUnprovenComponents).join(' '), /supported action lacks supported D07 physical/);
const bothDirectionsButSupported = structuredClone(valid);
bothDirectionsButSupported.interpretations[0].conflictingClaimIds = ['F-C04-1'];
assert.match(validate(bothDirectionsButSupported).join(' '), /status supported differs from evidence pair conflicted/);
const falseNumericAnswer = structuredClone(valid);
falseNumericAnswer.taskResponses.find(response => response.taskId === 'D02').values.press = 99;
assert.deepEqual(validate(falseNumericAnswer), []); // source correctness belongs to separately scored key
const unionValid = structuredClone(valid);
unionValid.snapshotId = 'SYNTHETIC_VALID_UNION_NOT_RESEARCH_OUTPUT';
unionValid.phase = 'union';
unionValid.agentId = unionContext.agentId;
unionValid.suppliedCardIds = unionContext.cardIds;
unionValid.sourceCoverage = world.cards.map(card => ({ cardId: card.id, disposition: 'used', reason: 'synthetic union contract fixture' }));
unionValid.taskResponses.push(
  { taskId: 'D09', values: { lineageCount: 1, maxQuantity: 1 }, evidence: { lineageCount: [], maxQuantity: [] }, missingDependencies: [] },
  { taskId: 'D10', values: { C06_C13: 'unknown', C13_C14: 'unknown' }, evidence: { C06_C13: [], C13_C14: [] }, missingDependencies: ['synthetic contract fixture leaves analogy scoring to key'] },
);
