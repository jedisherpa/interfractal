const unionWithInitialScope = structuredClone(valid);
unionWithInitialScope.phase = 'union';
unionWithInitialScope.agentId = unionContext.agentId;
assert.match(validate(unionWithInitialScope, unionContext).join(' '), /suppliedCardIds must exactly match|phase-required task/);
const revisedWithoutTrustedParent = structuredClone(unionValid);
revisedWithoutTrustedParent.phase = 'revised';
revisedWithoutTrustedParent.agentId = 'A1';
assert.match(validate(revisedWithoutTrustedParent, { ...unionContext, phase: 'revised', agentId: 'A1' }).join(' '), /trusted parent snapshot IDs missing/);
process.stdout.write('snapshot contract fixtures and mutations passed (synthetic; zero research outputs)\n');
