import assert from 'node:assert/strict';
import { join, resolve } from 'node:path';
import { readJson } from './package-utils.mjs';
import { validateJson } from './schema-validator.mjs';
import { validateSnapshotRecord } from './snapshot-contract.mjs';

const base = resolve(import.meta.dirname, '..');
const world = readJson(join(base, 'design/world.json'));
const allocations = readJson(join(base, 'design/allocations.json'));
const development = readJson(join(base, 'design/development-tasks.json'));
const schema = readJson(join(base, 'design/snapshot.schema.json'));
const packet = allocations.packets[0];
const validate = record => validateSnapshotRecord(record, schema, world, packet.cardIds, development);
const fixture = name => readJson(join(import.meta.dirname, 'fixtures', name));
const valid = fixture('SYNTHETIC_VALID_NOT_RESEARCH_OUTPUT.json');
assert.deepEqual(validate(valid), []);
const badFalse = fixture('SYNTHETIC_INVALID_FALSE_AS_UNKNOWN_NOT_RESEARCH_OUTPUT.json');
assert.match(validate(badFalse).join(' '), /outside enum/);
const badCommitment = fixture('SYNTHETIC_INVALID_ENDORSEMENT_AS_COMMITMENT_NOT_RESEARCH_OUTPUT.json');
assert.deepEqual(validateJson(badCommitment, schema), []); // semantic check adds value beyond JSON shape
assert.match(validate(badCommitment).join(' '), /does not positively support this exact predicate/);
const altered = structuredClone(valid);
altered.interpretations[0].supportingClaimIds = ['F-C18-1'];
assert.match(validate(altered).join(' '), /outside supplied cards/);
const missingNested = structuredClone(valid);
delete missingNested.interpretations[0].arguments;
assert.match(validate(missingNested).join(' '), /required/);
const unknownAsRefuted = structuredClone(valid);
unknownAsRefuted.interpretations[3].status = 'refuted';
assert.match(validate(unknownAsRefuted).join(' '), /refuted lacks negative evidence/);
const unknownWithEvidence = structuredClone(valid);
unknownWithEvidence.interpretations[3].supportingClaimIds = ['F-C04-1'];
assert.match(validate(unknownWithEvidence).join(' '), /unknown cannot carry positive or negative evidence/);
const wrongPlanCommitment = structuredClone(valid);
wrongPlanCommitment.interpretations[2].supportingClaimIds = ['F-C04-4'];
assert.match(validate(wrongPlanCommitment).join(' '), /does not positively support this exact predicate/);
const attributionAsAttestation = structuredClone(valid);
attributionAsAttestation.interpretations[1].sourceKind = 'model_attribution';
assert.match(validate(attributionAsAttestation).join(' '), /cannot become actor attestation/);
const unsupportedTask = structuredClone(valid);
unsupportedTask.taskResponses[0].taskId = 'D09';
assert.match(validate(unsupportedTask).join(' '), /outside initial-access allowlist/);
process.stdout.write('snapshot contract fixtures and mutations passed (synthetic; zero research outputs)\n');
